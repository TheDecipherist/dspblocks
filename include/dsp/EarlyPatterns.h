// The early-reflection pattern as DATA, kept away from every tank.
//
// A reverb has two separately audible halves. The early pattern says how big
// the space is and how hard its walls are; the tail says how long it rings.
// Welding one into the other is how a "plate" ends up with a hall's first
// 60 ms, and it is also how a genuinely recovered table ends up trapped inside
// whichever topology happened to be written first.
//
// So: `EarlyReflections` (in `Reverb.h`) is the PLAYER, this is the RECORD, and
// either tank - the Schroeder chain in `Reverb.h` or the figure-of-eight in
// `ReverbFigure8.h` - can be fed the same pattern.
//
// ---------------------------------------------------------------------------
// WHERE RECOVERED PATTERNS LIVE, AND WHY NOT HERE
//
// This library holds no `[FW]` data, deliberately: its README says so, and the
// reason is that a copy of a machine's table sitting in a shared library is a
// copy that drifts away from the extractor that produced it and loses the
// provenance line that makes it worth anything. A unit that has recovered its
// own pattern table passes it in. The Reverb 4000 is the worked example -
// `reverb4000/src/generated/R4kTables.h`, 31 distinct patterns of 21 taps,
// generated by `tools/extract_tables.py` from an 80-record table at image
// offset 0x72D30 whose layout is written out in that project's
// `docs/research.md` section 8 - and it drops straight into `load()` below.
//
// A WARNING that cost a day to be sure of. There is a SECOND table in that same
// image, at 0x0c6c54, that has been read as "the EARLYPAT early-reflection
// patterns, 20 records of 40 taps, stride 0x148" and used as such. It is not
// one. Walking that region at a 328-byte stride slices a heterogeneous pool of
// tables into records that are not records:
//
//   * 8 of the 20 have a "gain" array that is byte-identical to the machine's
//     40-float ALLPASS DIFFUSER COEFFICIENT pool (all of it inside
//     0.5120..0.6974, the Schroeder/Gardner range) - the same 120 bytes appear
//     at eight places in the image, and one of them is the pool the DSP reads
//     its diffuser coefficients from;
//   * record 3's "tap positions" are an exact arithmetic ramp, every step
//     0x140014, and its "gains" fit a single sinusoid of period 6.28 samples to
//     99.9 % of their energy: that is an oscillator table, not a room;
//   * 6 of the 20 share an identical position tail from index 15 onward.
//
// Recovered bytes, wrong reading. Feeding them to a reverb produces a
// scattering of taps that does not sound bad, which is exactly why it survived.
// If a pattern is going to be tagged `[FW]`, the record boundary has to be
// evidence too.
// ---------------------------------------------------------------------------
#pragma once
#include "Constants.h"
#include "Reverb.h"
#include <algorithm>
#include <cmath>

namespace dsp {

/** One early pattern.

    Times are in MILLISECONDS, not samples: a reflection pattern is a geometry
    and the geometry does not change with the sample rate. Gains are linear and
    SIGNED, because polarity is half of what makes a pattern sound like a room
    rather than like a flutter - a machine that stores its reflections as
    +-0.96 is storing polarity with a trim, and dropping the sign flattens it. */
struct EarlyPattern
{
    static constexpr int kMaxTaps = 40;   // see EarlyReflections::kMaxTaps

    int    numTaps = 0;
    /** The room scale the pattern's own source carries, if it carries one; 1.0
        if it does not. Multiplies nothing on its own - a unit decides whether to
        use it - but it is the field a recovered table's size marker goes in. */
    double sizeHint = 1.0;
    float  ms[kMaxTaps]   {};
    float  gain[kMaxTaps] {};

    void clear() { numTaps = 0; }
    void add (double timeMs, double linearGain)
    {
        if (numTaps >= kMaxTaps) return;
        ms[numTaps] = (float) timeMs;
        gain[numTaps] = (float) linearGain;
        ++numTaps;
    }
};

/** How the taps are spread across the two outputs.

    `Alternate` is the cheap one every implementation reaches for first and is
    fine for a dense pattern. `Mirrored` gives each tap a real position: early
    taps stay near the centre and later ones open out, which is what a room
    does, and it keeps the mono sum honest because both sides carry every tap. */
enum class EarlyStereo { Alternate, Mirrored, Mono };

/** Install a pattern into a player.

    `sizeScale` stretches the whole geometry - it is the Size control, and it
    multiplies times, never levels. `level` trims the whole pattern. Taps beyond
    the player's own capacity are dropped from the END, so the near reflections
    (the ones that carry the room's size) always survive. */
inline void load (EarlyReflections& er, const EarlyPattern& p,
                  double sizeScale = 1.0, float level = 1.0f,
                  EarlyStereo mode = EarlyStereo::Mirrored)
{
    er.clear();
    const int n = std::min (p.numTaps, EarlyReflections::kMaxTaps);
    for (int i = 0; i < n; ++i)
    {
        const float g = p.gain[i] * level;
        float l = g, r = g;
        if (mode == EarlyStereo::Alternate)
        {
            if (i & 1) l = 0.0f; else r = 0.0f;
        }
        else if (mode == EarlyStereo::Mirrored)
        {
            // Pan by index: tap 0 centred, later taps further out, alternating
            // sides. sin/cos so the pair is constant-power and the mono sum of
            // the pattern does not change as the width does.
            const double spread = (n > 1) ? (double) i / (double) (n - 1) : 0.0;
            const double angle = (kPi * 0.25) * (1.0 + ((i & 1) ? spread : -spread));
            l = g * (float) std::cos (angle) * 1.41421356f;
            r = g * (float) std::sin (angle) * 1.41421356f;
        }
        er.addTap (p.ms[i] * sizeScale, l, r);
    }
}

/** Build a pattern from NORMALISED tap positions.

    Several machines store reflection times as a fraction of a span rather than
    as an absolute time, so that one table can serve every room size. `spanMs`
    is what the fraction is a fraction OF, and a unit that does not know the
    span is not entitled to call the result `[FW]`: the positions are recovered,
    the span is a guess, and the two have to be tagged apart. */
inline EarlyPattern fromNormalised (const float* pos, const float* gains, int n, double spanMs)
{
    EarlyPattern p;
    n = std::min (n, EarlyPattern::kMaxTaps);
    for (int i = 0; i < n; ++i) p.add (pos[i] * spanMs, gains[i]);
    return p;
}

/** Build a pattern from taps already in samples at some design rate. The
    Reverb 4000's table is in samples at its DSP's 48 kHz base, for instance. */
inline EarlyPattern fromSamples (const float* samples, const float* gains, int n, double designRate)
{
    EarlyPattern p;
    n = std::min (n, EarlyPattern::kMaxTaps);
    const double k = 1000.0 / (designRate > 0 ? designRate : 48000.0);
    for (int i = 0; i < n; ++i) p.add (samples[i] * k, gains[i]);
    return p;
}

/** The library's own patterns. All `[EAR]`: they are the shape a room of that
    size has, spaced so that no two taps land on a simple ratio of each other,
    and they are what a unit with no recovered table of its own should use
    rather than inventing a fifth one. */
namespace earlyPatterns {

/** A small hard room: the first reflection arrives early and the pattern is
    over inside 40 ms. */
inline EarlyPattern smallRoom()
{
    EarlyPattern p; p.sizeHint = 0.6;
    const double t[] = { 4.3, 6.1, 8.9, 11.3, 13.7, 17.9, 21.1, 25.3, 29.7, 34.1, 38.9 };
    const double g[] = { 0.86, -0.71, 0.63, -0.55, 0.48, -0.42, 0.37, -0.31, 0.26, -0.21, 0.17 };
    for (int i = 0; i < 11; ++i) p.add (t[i], g[i]);
    return p;
}

/** A medium room, and the one to reach for when a machine prints "room" with no
    further evidence. */
inline EarlyPattern mediumRoom()
{
    EarlyPattern p; p.sizeHint = 1.0;
    const double t[] = { 7.9, 11.3, 15.7, 19.1, 23.9, 28.3, 33.7, 38.1, 43.9, 49.3, 55.1, 61.7 };
    const double g[] = { 0.79, -0.68, 0.61, -0.54, 0.47, -0.42, 0.36, -0.31, 0.27, -0.23, 0.19, -0.15 };
    for (int i = 0; i < 12; ++i) p.add (t[i], g[i]);
    return p;
}

/** A hall: a long gap before the first reflection, then a pattern that lasts
    long enough to hand over to a tail rather than to end. */
inline EarlyPattern hall()
{
    EarlyPattern p; p.sizeHint = 1.8;
    const double t[] = { 13.1, 19.7, 26.3, 33.1, 39.7, 47.3, 54.1, 61.9, 69.7, 78.1, 86.3, 95.9, 104.3, 113.9 };
    const double g[] = { 0.71, -0.64, 0.58, -0.53, 0.48, -0.43, 0.39, -0.35, 0.31, -0.28, 0.24, -0.21, 0.18, -0.15 };
    for (int i = 0; i < 14; ++i) p.add (t[i], g[i]);
    return p;
}

/** A plate has no early pattern worth the name - it is a sheet, not a room, and
    it is dense from the first millisecond. Three taps, close together, and a
    unit is expected to run this at a low level or not at all. */
inline EarlyPattern plate()
{
    EarlyPattern p; p.sizeHint = 0.4;
    const double t[] = { 1.7, 3.1, 5.3 };
    const double g[] = { 0.62, -0.44, 0.29 };
    for (int i = 0; i < 3; ++i) p.add (t[i], g[i]);
    return p;
}

} // namespace earlyPatterns
} // namespace dsp
